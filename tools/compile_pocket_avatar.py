#!/usr/bin/env python3
"""Compile retained DS head portraits to a small, immutable C pixel atlas.

Pillow is needed only to regenerate the checked-in header, never by firmware.
No artwork is generated or repainted: these are explicit source rectangles,
nearest-neighbour samples, and a shared 64-colour palette.
"""
from hashlib import sha256
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/images/ai-companions/avatar-whale-v1.png"
OUTPUT = ROOT / "assets/images/ai-companions/pocket_whale_pixels.h"
SOURCE_SHA = "a65788b97391806f309cf6039ae2ddb9b5a2d254749cb74d6ce20deacebdc14c"
SLEEP_SOURCE = ROOT / "assets/images/ai-companions/avatar-whale-sleep-v5.png"
SLEEP_SHA = "70e146ecb2e4220db28928235a1d7556dd6b411f17424a867ecd80d27a42e382"
SLEEP_BOUNDS = (95, 67, 1307, 1070)
GRID = 60
# sleep, idle, focused/busy, awaiting approval, happy, apologetic/error.
# Bounds were checked against each connected opaque portrait, not equal cells.
BOUNDS = [
    (367, 893, 680, 1164), (18, 11, 343, 289),
    (19, 304, 341, 584), (20, 602, 336, 878),
    (366, 11, 687, 289), (363, 602, 680, 878),
]


def main():
    assert sha256(SOURCE.read_bytes()).hexdigest() == SOURCE_SHA, "Source changed; review bounds"
    source = Image.open(SOURCE).convert("RGBA")
    samples = []
    # Identical scale and baseline, with space above the head for status marks.
    factor = 56 / 325
    for left, top, right, bottom in BOUNDS:
        width, height = right - left, bottom - top
        offset_x = (GRID - width * factor) / 2
        offset_y = 58 - height * factor
        frame = []
        for y in range(GRID):
            for x in range(GRID):
                sx = int((x + .5 - offset_x) / factor)
                sy = int((y + .5 - offset_y) / factor)
                inside = offset_x <= x + .5 < offset_x + width * factor and offset_y <= y + .5 < 58
                rgba = source.getpixel((left + sx, top + sy)) if inside else (0, 0, 0, 0)
                frame.append(rgba[:3] if rgba[3] >= 192 else None)
        samples.append(frame)
    # Preserve the original shared palette and all five other portrait bytes.
    opaque = [rgb for frame in samples for rgb in frame if rgb is not None]
    strip = Image.new("RGB", (len(opaque), 1))
    strip.putdata(opaque)
    quantized = strip.quantize(colors=64, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = quantized.getpalette()[:64 * 3]
    colours = [tuple(palette[i:i + 3]) for i in range(0, len(palette), 3)]
    assert sha256(SLEEP_SOURCE.read_bytes()).hexdigest() == SLEEP_SHA, "Sleep source changed; review bounds"
    sleep = Image.open(SLEEP_SOURCE).convert("RGBA")
    left, top, right, bottom = SLEEP_BOUNDS
    factor = 54 / (right - left)
    offset_x = 3
    offset_y = 58 - (bottom - top) * factor
    replacement = []
    for y in range(GRID):
        for x in range(GRID):
            sx = int((x + .5 - offset_x) / factor)
            sy = int((y + .5 - offset_y) / factor)
            inside = offset_x <= x + .5 < 57 and offset_y <= y + .5 < 58
            rgba = sleep.getpixel((left + sx, top + sy)) if inside else (0, 0, 0, 0)
            replacement.append(rgba[:3] if rgba[3] >= 192 else None)
    samples[0] = replacement
    def index(rgb):
        if rgb is None:
            return 0
        return 16 + min(range(len(colours)), key=lambda i: sum((a - b) ** 2 for a, b in zip(rgb, colours[i])))
    lines = ["// Generated by tools/compile_pocket_avatar.py; do not repaint this atlas.",
             "// Source SHA-256: " + SOURCE_SHA,
             "// Sleeping head SHA-256: " + SLEEP_SHA, "#pragma once", "",
             "static const uint32_t POCKET_WHALE_PALETTE[64] = {"]
    for rgb in colours:
        lines.append("    0x%02X%02X%02X," % rgb)
    lines += ["};", "", "static const uint8_t POCKET_WHALE_PIXELS[6][60 * 60] = {"]
    for frame in samples:
        lines.append("    {")
        for y in range(GRID):
            lines.append("        " + ",".join(str(index(rgb)) for rgb in frame[y * GRID:(y + 1) * GRID]) + ",")
        lines.append("    },")
    lines += ["};", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"Compiled six source portraits: {6 * GRID * GRID + 64 * 4} Flash bytes, no decode buffer")


if __name__ == "__main__":
    main()
